#pragma once

/**
 * @brief 設定画面を開く。既に開いていれば手前に出す。
 *
 * @details
 * 項目は 2 つのタブに分ける(項目を足しても、画面が縦に伸びないように)。いつも「一般」のタブで開く。
 * どのタブも、OBS の設定画面と同じく、見出し付きの枠の中に、左の列に項目名、右の列に入力欄と説明文を置く。
 * - タブ「一般」(画像の表示に関わる設定)
 *   - 枠「表示/非表示のタイミング」
 *     - 表示時間(秒、0〜999。0 なら手動でのみ非表示)
 *     - スタジオモードでもすぐに配信画面に表示する(オン/オフ。既定オフ。オンならスタジオモードで「シーンを複製」がオンでも、画像をすぐプログラムに表示する)
 *   - 枠「自動調整」(表示するたびにプラグインが自動で行うこと)
 *     - 最大サイズ(キャンバスの面積に対する割合、10〜100%。横にその大きさのピクセル数を薄い文字で表示。
 *       境界の種類が「自動」のときのみ有効と明記)
 *     - 常に最前面に表示する(オン/オフ)
 * - タブ「表示履歴」(表示履歴のドックに並ぶ、保存した画像に関わること)
 *   - 枠「保存した画像」
 *     - ドラッグ&ドロップした画像をすぐに表示する(オン/オフ。既定オフ。オフなら表示履歴に足すだけ。項目名から分かるので説明文はない)
 *     - 保存フォルダを開く(ボタン。押すとその場で、画像の保存フォルダを OS のファイルの画面で開く。フォルダがなければ作る)
 * 枠の中の説明文は、項目と区別できるよう薄い文字で表示する。
 * 説明文は入力欄のすぐ下に詰めて置き、項目どうしの間は広く空ける(説明文がどの項目のものか、位置で分かるように)。
 * タブの下に、反映のタイミングの案内を通常の濃さで表示する(どのタブの設定にも当てはまるので、タブを切り替えても消えない)。
 * その下(ボタンの上)に、バージョン(例: テスト版は v0.1.0-beta、完成版は v0.1.0)と、マニュアル・不具合・ご要望のフォームへのリンクを薄い文字で表示する。
 * 不具合・ご要望のリンクは、プラグインの版・OBS のバージョン・OS を入力した状態でフォームを開く。
 * リンク先は OBS の言語設定に合わせて変わる(日本語は日本語のマニュアル、それ以外は英語の README)。
 *
 * ボタン(並びは OBS の設定画面に合わせる):
 * - OK: 保存して閉じる
 * - キャンセル(Esc キー・右上の×も同じ): 保存せずに閉じる
 * - 適用: 保存して開いたまま(設定を試しながら画像を貼れる)
 * - 既定値: 開いているタブの、画面上の値だけ既定値に戻す(OK か適用を押すまで保存しない)
 *
 * フェードの長さはプラグインの設定に含めず、OBS 標準の表示/非表示トランジションで変える(変え方はマニュアルに書く)。
 * 開いたまま OBS を操作できる(モードレス)。同時に開くのは 1 つだけ。
 *
 * @note 呼び出し元: plugin-main.cpp の add_tools_submenu()(「ツール」メニューの「設定...」)。
 * @note スレッド: UI スレッドから呼ぶこと。
 */
void open_settings_dialog();

/**
 * @brief 設定画面が開いていれば、保存せずに閉じる。開いていなければ何もしない。
 *
 * @details OBS の終了時に呼ぶ。開いたままの画面が、片付けの途中の OBS を触らないようにするため。
 *
 * @note 呼び出し元: plugin-main.cpp(終了時・プラグイン解放時)。
 * @note スレッド: UI スレッドから呼ぶこと。
 */
void close_settings_dialog();

/**
 * @file settings-dialog.hpp
 * @brief 設定画面(ダイアログ)の公開窓口。
 *
 * @details 実装は settings-dialog.cpp。呼び出し元は plugin-main.cpp(「ツール」メニュー)。
 */

#pragma once

#include "image-display.hpp"

#include <functional>

/**
 * @brief 設定画面から、plugin-main.cpp に処理を頼むための関数の組。
 *
 * @details 設定画面は画面だけを受け持ち、画像の削除のような処理は呼び出し元に任せる。
 *          どの関数も UI スレッドで呼ばれる。空のままの関数は呼ばない。
 */
struct SettingsDialogCallbacks {
	/**
	 * @brief 表示履歴の画像を、すべてごみ箱に移す。「表示履歴を全て削除」で、確認の画面で OK を押したときに呼ぶ。
	 */
	std::function<void()> delete_all_history;

	/// @brief プラグインの画像ソースの一覧を返す(list_clipboard_sources())。「ソース」のタブを開いたときと「更新」で呼ぶ。
	std::function<std::vector<ClipboardSourceInfo>()> list_sources;

	/**
	 * @brief 画像ソースを 1 つ、すべてのシーンから削除する(remove_clipboard_source())。
	 * @details 「ソース」のタブのごみ箱のボタンで、確認の画面で OK を押したときに呼ぶ。引数はソースの名前。
	 */
	std::function<void(const std::string &name)> remove_source;

	/// @brief 画像ソースをすべて削除する(remove_all_clipboard_sources())。「全て削除」で、確認の画面で OK を押したときに呼ぶ。
	std::function<void()> remove_all_sources;
};

/**
 * @brief 設定画面から頼む処理を登録する。
 *
 * @param callbacks 設定画面から頼む処理。
 *
 * @note 呼び出し元: plugin-main.cpp の obs_module_load()。
 * @note スレッド: UI スレッドから呼ぶこと。
 */
void settings_dialog_register(SettingsDialogCallbacks callbacks);

/**
 * @brief 設定画面を開く。既に開いていれば手前に出す。
 *
 * @details
 * 項目は 3 つのタブに分ける(項目を足しても、画面が縦に伸びないように)。いつも「一般」のタブで開く。
 * どのタブも、OBS の設定画面と同じく、見出し付きの枠の中に、左の列に項目名、右の列に入力欄と説明文を置く。
 * - タブ「一般」(画像の表示に関わる設定)
 *   - 枠「表示/非表示のタイミング」
 *     - 表示時間(秒、0〜999。0 なら手動でのみ非表示)
 *     - スタジオモードでもすぐに配信画面に表示する(オン/オフ。既定オフ。オンならスタジオモードで「シーンを複製」がオンでも、画像をすぐプログラムに表示する)
 *   - 枠「自動調整」(表示するたびにプラグインが自動で行うこと)
 *     - 最大サイズ(キャンバスの面積に対する割合、10〜100%。横にその大きさのピクセル数を薄い文字で表示。
 *       境界の種類が「自動」のときのみ有効と明記)
 *     - 常に最前面に表示する(オン/オフ)
 * - タブ「表示履歴」(表示履歴のドックに並ぶ、保存した画像に関わること)
 *   - 枠「画像の保存」
 *     - 上限枚数(1〜999 枚。既定 50 枚。超えた古い画像は自動で削除されると説明文に書く)
 *     - 保存フォルダを開く(ボタン。押すとその場で、画像の保存フォルダを OS のファイルの画面で開く。フォルダがなければ作る)
 *     - 表示履歴を全て削除(ボタン。確認の画面で OK を押すと、その場で callbacks.delete_all_history を呼ぶ)
 * - タブ「ソース」(プラグインの画像ソースの一覧。枠は使わず、一覧をタブいっぱいに出す)
 *   - 1 行 = 1 つの画像ソース(無印と番号付き)。番号の大きい順。列は ソース・シーン・最終表示・表示状態・削除
 *     - ソース: 「Clipboard Image 99」まで入る幅
 *     - シーン: 置かれているシーンを並べる(別キャンバスのシーンはキャンバスの名前を添える)。入りきらなければ「…」で省略し、
 *       マウスを乗せると全部出す
 *     - 最終表示: 参照している画像ファイルの保存日時(2026-11-22 の形)
 *     - 表示状態: どこかのシーンで表示中なら、目のアイコンを出す(表示だけで、押しても何もしない)
 *     - 削除: ごみ箱のボタン。確認の画面で OK を押すと、その場で callbacks.remove_source を呼び、一覧を読み直す
 *   - 一覧の下に「更新」(一覧を読み直す)と「全て削除」(確認の画面で OK を押すと callbacks.remove_all_sources)
 *   - 一覧は、タブを開いたときと「更新」を押したときだけ読み込む(見えていない画面のための処理をしないため)
 *   - 画像ソースが 1 つもなければ、一覧の代わりに案内を出す
 * 枠の中の説明文は、項目と区別できるよう薄い文字で表示する。
 * 説明文は入力欄のすぐ下に詰めて置き、項目どうしの間は広く空ける(説明文がどの項目のものか、位置で分かるように)。
 * タブの下に、反映のタイミングの案内を通常の濃さで表示する(どのタブの設定にも当てはまるので、タブを切り替えても消えない)。
 * その下(ボタンの上)に、バージョン(例: テスト版は v0.1.0-beta、完成版は v0.1.0)と、マニュアル・不具合・ご要望のフォームへのリンクを薄い文字で表示する。
 * 不具合・ご要望のリンクは、プラグインの版・OBS のバージョン・OS を入力した状態でフォームを開く。
 * リンク先は OBS の言語設定に合わせて変わる(日本語は日本語のマニュアル、それ以外は英語の README)。
 *
 * ボタン(並びは OBS の設定画面に合わせる):
 * - OK: 保存して閉じる
 * - キャンセル(Esc キー・右上の×も同じ): 保存せずに閉じる
 * - 適用: 保存して開いたまま(設定を試しながら画像を貼れる)
 * - 既定値: 開いているタブの、画面上の値だけ既定値に戻す(OK か適用を押すまで保存しない)。「ソース」のタブでは押せない
 *
 * フェードの長さはプラグインの設定に含めず、OBS 標準の表示/非表示トランジションで変える(変え方はマニュアルに書く)。
 * 開いたまま OBS を操作できる(モードレス)。同時に開くのは 1 つだけ。
 *
 * @note 呼び出し元: plugin-main.cpp の add_tools_submenu()(「ツール」メニューの「設定...」)。
 * @note スレッド: UI スレッドから呼ぶこと。
 */
void open_settings_dialog();

/**
 * @brief 設定画面が開いていれば、保存せずに閉じる。開いていなければ何もしない。
 *
 * @details OBS の終了時に呼ぶ。開いたままの画面が、片付けの途中の OBS を触らないようにするため。
 *
 * @note 呼び出し元: plugin-main.cpp(終了時・プラグイン解放時)。
 * @note スレッド: UI スレッドから呼ぶこと。
 */
void close_settings_dialog();
